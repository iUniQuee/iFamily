// Харьяалахын тийн ялгалын дүрэм — сервер ба клиент хоёулаа ижил байх ёстой
import { readFileSync } from 'node:fs';
import { genitiveName } from './src/genitive.js';
let bad = 0;
const ok = (n, want) => {
  const got = genitiveName(n);
  const pass = got === want;
  if (!pass) bad++;
  console.log((pass ? '✓ ' : '✗ ') + n + ' → ' + got + (pass ? '' : ' (хүлээсэн: ' + want + ')'));
};
console.log('1) Эр үг / эм үг');
ok('Болд', 'Болдын');
ok('Сүрэн', 'Сүрэнгийн');
ok('Баярсайхан', 'Баярсайханы');
ok('Намжил', 'Намжилын');
console.log('2) Ж, Ч, Ш, Г, Х, Ь, И-ээр төгссөн');
ok('Батбаяр', 'Батбаярын');
ok('Баяржаргал', 'Баяржаргалын');
ok('Уранчимэг', 'Уранчимэгийн');
ok('Гансүх', 'Гансүхийн');
ok('Мягмардож', 'Мягмардожийн');
console.log('3) Гээгдэх эгшиг');
ok('Хатанбаатар', 'Хатанбаатрын');
ok('Сүхбаатар', 'Сүхбаатрын');
ok('Ганбаатар', 'Ганбаатрын');
console.log('4) Зөөлрүүлэх тэмдэг «ь»');
ok('Төмөрбань', 'Төмөрбанийн');
ok('Ань', 'Анийн');
console.log('5) Бусад DB-ийн эцгийн нэрс');
[['Дөлгөөн','Дөлгөөнгийн'],['Бямбасүрэн','Бямбасүрэнгийн'],['Шагдарсүрэн','Шагдарсүрэнгийн'],
 ['Эрдэнэ','Эрдэнийн'],['Ганхүү','Ганхүүгийн'],['Билгүүдэй','Билгүүдэйн'],['Шилүүгэй','Шилүүгэйн'],
 ['Төмөрөө','Төмөрөөгийн'],['Баяраа','Баяраагийн'],['Дамдин','Дамдины'],['Сонин','Сонины'],
 ['Цагаан','Цагааны'],['Лайшив','Лайшивын'],['Мажиг','Мажигийн'],['Өвөөаав','Өвөөаавын']]
  .forEach(([a,b]) => ok(a,b));
// Клиент дээрх хуулбар сервертэйгээ ижил эсэх
const c = readFileSync('public/tree_client.js', 'utf8');
const server = readFileSync('src/genitive.js', 'utf8');
const fs0 = server.indexOf('function genitiveName');
const body = server.slice(fs0, server.indexOf('\n}\n', fs0) + 3);
const same = c.includes(body);
if (!same) bad++;
console.log((same ? '✓ ' : '✗ ') + 'клиент ба серверийн дүрэм ижил');
process.exit(bad ? 1 : 0);
